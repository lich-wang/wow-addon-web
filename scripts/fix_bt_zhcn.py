changed_count = 0
fmt_mismatch = 0
seen = set()

for k, old_v in entries:
    if k in seen:
        continue
    seen.add(k)
    new_v = clean_machine_zh(k, old_v)

    # Verify format tokens match exactly
    en_tokens = get_format_tokens(k)
    zh_tokens = get_format_tokens(new_v)
    if en_tokens != zh_tokens:
        print(f"[WARN] Format token mismatch for {repr(k)}: {en_tokens} vs {zh_tokens} in {repr(new_v)}")
        fmt_mismatch += 1

    if new_v != old_v:
        changed_count += 1
    out_lines.append(f'L[{encode_lua_str(k)}] = {encode_lua_str(new_v)}')

# Add any extra keys in CURATED not yet in seen
for k, v in CURATED.items():
    if k not in seen:
        seen.add(k)
        out_lines.append(f'L[{encode_lua_str(k)}] = {encode_lua_str(v)}')
        changed_count += 1

final_text = '\n'.join(out_lines) + '\n'

