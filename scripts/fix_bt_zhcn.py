def get_format_tokens(text):
    # Match Lua printf specifiers: %%, %s, %d, %2d, %02d, %.1f, %.0f, etc.
    return [t for t in re.findall(r'%[-+0 #]*\d*(?:\.\d+)?[sdifxXouceEgG%]', text) if t != '%%']

